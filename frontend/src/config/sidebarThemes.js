export const sidebarThemeMap = SIDEBAR_THEMES.reduce((themeMap, theme) => {
  themeMap[theme.id] = theme;
  return themeMap;
}, {});

export const getSidebarTheme = (themeId) => {
  return sidebarThemeMap[themeId] ?? sidebarThemeMap[DEFAULT_SIDEBAR_THEME];
};
