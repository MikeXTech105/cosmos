// @vitest-environment jsdom
import { act, cleanup, fireEvent, render, screen, waitFor, within } from "@testing-library/react";
import { MemoryRouter, useNavigate } from "react-router-dom";
import { afterEach, beforeEach, describe, expect, it, vi } from "vitest";
const f = vi.hoisted(() => ({ access: {}, runtime: {}, saved: false, contextFails: false, api: Object.fromEntries(["list", "context", "complete", "release", "bom"].map(name => [name, vi.fn()])) }));
vi.mock("../../../services/manufacturing/productionOrderService", () => ({ default: f.api }));
vi.mock("../../../hooks/useProductionRuntime", () => ({ default: () => f.runtime }));
vi.mock("../../../hooks/useCapabilities", () => ({ default: () => ({ canView: true, canApprove: true }) }));
vi.mock("../../../utils/userScope", () => ({ getUserScope: () => "test-operator", getTrustedDraftScope: () => null }));
vi.mock("../orders/orderHooks", async original => ({ ...(await original()), useOrderCapabilities: () => f.access, useOrderLookupAccess: () => ({ boms: false }), useItemLabels: () => Object.assign(id => `Item ${id}`, { canView: true, unitLabel: () => "PCS" }) }));
vi.mock("../../../components/common/AppSelect", () => ({ default: ({ label, value, onChange, options, disabled }) => <label>{label}<select aria-label={label} value={value} disabled={disabled} onChange={event => onChange(event.target.value)}>{options.map(option => <option key={option.value} value={option.value}>{option.label}</option>)}</select></label> }));
vi.mock("sonner", () => ({ toast: { success: vi.fn() } }));
import ProductionDeskPage from "./ProductionDeskPage";
const order = { id: 7, orderNumber: "PRO-7", status: 2, version: "v1", itemId: 4, unitId: 2, plannedQuantity: "100", releasedQuantity: "100", remainingQuantity: "100", completedQuantity: "0", rejectedQuantity: "0", businessDate: "2026-10-27", dueDate: "2026-10-30", machineId: 1, mouldId: 2, shiftId: 3 };
const page = (items, total = items.length) => ({ data: { items, totalCount: total, pageNumber: 1, pageSize: 20, totalPages: Math.ceil(total / 20) } });
const context = row => ({ data: { order: row, materials: [{ id: 11, itemId: 9, unitId: 3, requiredQuantity: "10", consumedQuantity: "0", baselineOutputQuantity: "0", baselineExpectedQuantity: "0" }], completions: [] } });
function NavigationProbe() { const navigate = useNavigate(); return <button onClick={() => navigate("/manufacturing/daily?status=3")}>Browser navigation probe</button>; }
const mount = (url = "/manufacturing/daily", probe = false) => render(<MemoryRouter initialEntries={[url]}>{probe && <NavigationProbe />}<ProductionDeskPage /></MemoryRouter>);
beforeEach(() => {
  sessionStorage.clear();
  localStorage.clear();
  Object.values(f.api).forEach(mock => mock.mockReset());
  f.access = { canView: true, canCreate: true, canApprove: true };
  f.runtime = { runtime: { businessDate: "2026-10-28", businessTimeZone: "India Standard Time", browserTimeZone: "Asia/Kolkata" }, error: "", loading: false, reload: vi.fn() };
  f.saved = false; f.contextFails = false;
  f.api.list.mockImplementation(async () => page([{ ...order, version: f.saved ? "v2" : "v1", remainingQuantity: f.saved ? "89" : "100" }]));
  f.api.context.mockImplementation(async () => { if (f.contextFails) throw new Error("Readback unavailable"); return context({ ...order, version: f.saved ? "v2" : "v1" }); });
  f.api.complete.mockImplementation(async () => { f.saved = true; return { data: { id: 7, version: "v2" } }; });
});
afterEach(cleanup);
const enter = async (good = "10", reject = "1") => {
  await screen.findByRole("textbox", { name: "Accepted today PRO-7" });
  fireEvent.change(screen.getByRole("textbox", { name: "Accepted today PRO-7" }), { target: { value: good } });
  fireEvent.change(screen.getByRole("textbox", { name: "Rejected today PRO-7" }), { target: { value: reject } });
  fireEvent.click(screen.getByRole("button", { name: "Review entry" }));
  return screen.findByRole("dialog");
};
describe("daily production desk against actual command modal", () => {
  it("recovers a company-scoped versioned draft only after explicit review and never posts it", async () => {
    f.runtime.runtime.companyKey = "fixture-company-a";
    const first = mount();
    const input = await screen.findByRole("textbox", { name: "Accepted today PRO-7" });
    fireEvent.change(input, { target: { value: "10.000001" } });
    expect(screen.getByText(/pending ·/)).toBeTruthy();
    const dateControl = screen.getByLabelText("Entry date");
    const originalDate = dateControl.textContent;
    expect(dateControl.disabled).toBe(true);
    fireEvent.click(dateControl);
    expect(screen.queryByRole("dialog")).toBeNull();
    expect(dateControl.textContent).toBe(originalDate);
    expect(screen.getByText(/Review or discard pending entries before changing/)).toBeTruthy();
    fireEvent.click(screen.getByRole("button", { name: "Keep draft" }));
    first.unmount();
    const restored = mount();
    await screen.findByText("Saved production draft available");
    expect(f.api.complete).not.toHaveBeenCalled();
    fireEvent.click(screen.getByRole("button", { name: "Recover draft" }));
    await waitFor(() => expect(screen.getByRole("textbox", { name: "Accepted today PRO-7" }).value).toBe("10.000001"));
    expect(f.api.complete).not.toHaveBeenCalled();
    restored.unmount();
    f.runtime.runtime.companyKey = "fixture-company-b";
    mount();
    await screen.findByRole("textbox", { name: "Accepted today PRO-7" });
    expect(screen.queryByText("Saved production draft available")).toBeNull();
    expect(screen.getByRole("textbox", { name: "Accepted today PRO-7" }).value).toBe("");
  });
  it("prefills company date/time and entered quantities, requires actual review, then posts exact payload once", async () => {
    mount();
    const dialog = within(await enter("10.000001", "0.000001"));
    expect(f.api.complete).not.toHaveBeenCalled();
    expect(dialog.getByLabelText(/Accepted good output/).value).toBe("10.000001");
    expect(dialog.getByLabelText(/Rejected output/).value).toBe("0.000001");
    expect(dialog.getByLabelText(/Actual timestamp with UTC offset/).value).toMatch(/^2026-10-28T\d\d:\d\d:00\+05:30$/);
    expect(dialog.getByLabelText(/Consumed · Item #9/).value).toBe("");
    fireEvent.click(dialog.getByRole("button", { name: "Actual consumption matches expected" }));
    expect(dialog.getByLabelText(/Consumed · Item #9/).value).toBe("1");
    fireEvent.submit(dialog.getByRole("button", { name: "Save production" }).closest("form"));
    await waitFor(() => expect(f.api.complete).toHaveBeenCalledOnce());
    expect(f.api.complete.mock.calls[0][1]).toMatchObject({ version: "v1", businessDate: "2026-10-28", goodOutput: "10.000001", rejectedOutput: "0.000001", materials: [{ itemId: 9, unitId: 3, consumedQuantity: "1", scrapQuantity: "0", returnedQuantity: "0" }] });
    await waitFor(() => expect(screen.queryByRole("dialog")).toBeNull());
    expect(screen.getByRole("textbox", { name: "Accepted today PRO-7" }).value).toBe("");
  });
  it("retains the original completion key on an unknown retry and blocks duplicates after failed readback", async () => {
    f.api.complete.mockRejectedValueOnce(new Error("Network result unknown")).mockImplementationOnce(async () => { f.saved = true; f.contextFails = true; return { data: { id: 7 } }; });
    mount(); const dialog = within(await enter());
    fireEvent.change(dialog.getByLabelText(/Consumed · Item #9/), { target: { value: "1" } });
    const form = dialog.getByRole("button", { name: "Save production" }).closest("form");
    fireEvent.submit(form);
    await dialog.findByText(/The previous outcome is unknown/);
    fireEvent.submit(form);
    await dialog.findByText(/The command completed, but refreshing its order context failed/);
    expect(f.api.complete.mock.calls[0][1].idempotencyKey).toBe(f.api.complete.mock.calls[1][1].idempotencyKey);
    fireEvent.submit(form); expect(f.api.complete).toHaveBeenCalledTimes(2);
    expect(screen.getByRole("tab", { name: "Kanban board" }).disabled).toBe(true);
    f.contextFails = false;
    fireEvent.click(dialog.getByRole("button", { name: "Reload and review outcome" }));
    await waitFor(() => expect(screen.queryByRole("dialog")).toBeNull());
    expect(f.api.complete).toHaveBeenCalledTimes(2);
  });
  it("does not fetch orders or fabricate an empty stock state when company setup is missing", () => {
    f.runtime = { runtime: null, error: "Manufacturing catalog company scope is not configured.", loading: false, reload: vi.fn() };
    mount();
    expect(screen.getAllByText("Company setup needs attention").length).toBeGreaterThan(0);
    expect(screen.queryByText("No matching orders")).toBeNull();
    expect(f.api.list).not.toHaveBeenCalled();
    expect(f.api.context).not.toHaveBeenCalled();
  });
  it("masks protected data without view and disables entry for view-only users", async () => {
    f.access.canView = false; const rendered = mount();
    expect(f.api.list).not.toHaveBeenCalled();
    expect(screen.getByText(/do not have permission/)).toBeTruthy();
    rendered.unmount(); f.access.canView = true; f.access.canApprove = false; mount();
    await screen.findByRole("textbox", { name: "Accepted today PRO-7" });
    expect(screen.getByRole("textbox", { name: "Accepted today PRO-7" }).disabled).toBe(true);
    expect(screen.queryByRole("button", { name: "Review entry" })).toBeNull();
  });
  it("supports sheet paste and Enter navigation without posting or rounding quantities", async () => {
    f.api.list.mockResolvedValue(page([order, { ...order, id: 8, orderNumber: "PRO-8" }]));
    mount(); const first = await screen.findByRole("textbox", { name: "Accepted today PRO-7" });
    fireEvent.paste(first, { clipboardData: { getData: () => "10.000001\t0.000001\n2\t0" } });
    expect(first.value).toBe("10.000001");
    expect(screen.getByRole("textbox", { name: "Rejected today PRO-7" }).value).toBe("0.000001");
    expect(screen.getByRole("textbox", { name: "Accepted today PRO-8" }).value).toBe("2");
    fireEvent.keyDown(first, { key: "Enter" });
    expect(document.activeElement).toBe(screen.getByRole("textbox", { name: "Accepted today PRO-8" }));
    expect(f.api.complete).not.toHaveBeenCalled();
  });
  it("rejects a stale row before opening approval or silently rebasing its entered quantities", async () => {
    f.api.context.mockResolvedValue(context({ ...order, version: "v2" }));
    mount();
    await screen.findByRole("textbox", { name: "Accepted today PRO-7" });
    fireEvent.change(screen.getByRole("textbox", { name: "Accepted today PRO-7" }), { target: { value: "10" } });
    fireEvent.click(screen.getByRole("button", { name: "Review entry" }));
    await screen.findByText(/This order changed. Refresh and review/);
    expect(screen.queryByRole("dialog")).toBeNull();
    expect(f.api.complete).not.toHaveBeenCalled();
  });
  it("Kanban reads actual paged statuses and opens release review on a keyboard move without mutating status", async () => {
    f.api.list.mockImplementation(async ({ status }) => page(Number(status) === 1 ? [{ ...order, status: 1 }] : []));
    f.api.context.mockResolvedValue(context({ ...order, status: 1, bomId: 5 }));
    mount("/manufacturing/daily?view=board");
    const lane = within(await screen.findByRole("region", { name: "To approve" }));
    await lane.findByText("PRO-7");
    await waitFor(() => expect(f.api.list).toHaveBeenCalledTimes(6));
    expect(f.api.list.mock.calls.map(call => call[0].status).sort()).toEqual([1, 2, 3, 4, 5, 6]);
    fireEvent.change(lane.getByRole("combobox", { name: "Move order PRO-7" }), { target: { value: "2" } });
    fireEvent.click(lane.getByRole("button", { name: "Move", exact: true }));
    const dialog = within(await screen.findByRole("dialog"));
    expect(dialog.getByLabelText(/Approved release quantity/).value).toBe("100");
    expect(f.api.release).not.toHaveBeenCalled(); expect(f.api.complete).not.toHaveBeenCalled();
  });
  it("reviews selected sheet rows in order and only advances after the previous saved order is read back", async () => {
    const saved = new Set();
    const orders = [order, { ...order, id: 8, orderNumber: "PRO-8" }];
    const latest = row => ({ ...row, version: saved.has(row.id) ? "v2" : "v1" });
    f.api.list.mockImplementation(async () => page(orders.map(latest)));
    f.api.context.mockImplementation(async id => context(latest(orders.find(row => row.id === id))));
    f.api.complete.mockImplementation(async id => { saved.add(id); return { data: { id } }; });
    mount(); const first = await screen.findByRole("textbox", { name: "Accepted today PRO-7" });
    fireEvent.paste(first, { clipboardData: { getData: () => "10\t0\n2\t0" } });
    fireEvent.click(screen.getByRole("checkbox", { name: "Select for review PRO-7" }));
    fireEvent.click(screen.getByRole("checkbox", { name: "Select for review PRO-8" }));
    fireEvent.click(screen.getByRole("button", { name: "Review selected (2)" }));
    let dialog = within(await screen.findByRole("dialog"));
    expect(dialog.getByLabelText(/Accepted good output/).value).toBe("10");
    fireEvent.click(dialog.getByRole("button", { name: "Actual consumption matches expected" }));
    fireEvent.submit(dialog.getByRole("button", { name: "Save production" }).closest("form"));
    await waitFor(() => expect(within(screen.getByRole("dialog")).getByLabelText(/Accepted good output/).value).toBe("2"));
    expect(f.api.complete).toHaveBeenCalledOnce();
    expect(f.api.complete.mock.calls[0][0]).toBe(7);
    dialog = within(screen.getByRole("dialog"));
    fireEvent.click(dialog.getByRole("button", { name: "Actual consumption matches expected" }));
    fireEvent.submit(dialog.getByRole("button", { name: "Save production" }).closest("form"));
    await waitFor(() => expect(screen.queryByRole("dialog")).toBeNull());
    expect(f.api.complete.mock.calls.map(call => call[0])).toEqual([7, 8]);
    expect(f.api.complete.mock.calls[0][1].idempotencyKey).not.toBe(f.api.complete.mock.calls[1][1].idempotencyKey);
  });
  it("a dragged card opens the server-backed release review without posting on drop", async () => {
    f.api.list.mockImplementation(async ({ status }) => page(Number(status) === 1 ? [{ ...order, status: 1 }] : []));
    f.api.context.mockResolvedValue(context({ ...order, status: 1 }));
    mount("/manufacturing/daily?view=board");
    const ready = await screen.findByRole("region", { name: "Ready to start" });
    await within(ready).findByText("No orders in this column");
    fireEvent.drop(ready, { dataTransfer: { getData: () => JSON.stringify({ id: 7, status: 1 }) } });
    const dialog = within(await screen.findByRole("dialog"));
    expect(dialog.getByLabelText(/Approved release quantity/).value).toBe("100");
    expect(f.api.context).toHaveBeenCalledWith(7, expect.objectContaining({ signal: expect.any(AbortSignal) }));
    expect(f.api.release).not.toHaveBeenCalled();
    expect(f.api.complete).not.toHaveBeenCalled();
  });
  it("paginates each Kanban lane independently and locks duplicate load-more requests", async () => {
    let finish;
    f.api.list.mockImplementation(async ({ status, pageNumber }) => {
      if (Number(status) !== 2) return page([]);
      if (pageNumber === 2) return new Promise(resolve => { finish = resolve; });
      return page(Array.from({ length: 12 }, (_, index) => ({ ...order, id: index + 10, orderNumber: `PAGE-${index + 10}` })), 13);
    });
    mount("/manufacturing/daily?view=board");
    const lane = within(await screen.findByRole("region", { name: "Ready to start" }));
    const more = await lane.findByRole("button", { name: "Load more" });
    expect(lane.getAllByRole("article")).toHaveLength(12);
    fireEvent.click(more); fireEvent.click(more);
    expect(f.api.list.mock.calls.filter(call => call[0].pageNumber === 2)).toHaveLength(1);
    await act(async () => finish(page([{ ...order, id: 22, orderNumber: "PAGE-22" }], 13)));
    expect(lane.getAllByRole("article")).toHaveLength(13);
    expect(lane.queryByRole("button", { name: "Load more" })).toBeNull();
    expect(lane.getByText("13 shown of 13 orders")).toBeTruthy();
  });
  it("supports a direct board route and arrow-key tabs with an associated panel", async () => {
    f.api.list.mockImplementation(async () => page([]));
    mount("/manufacturing/board");
    const board = screen.getByRole("tab", { name: "Kanban board" });
    expect(board.getAttribute("aria-selected")).toBe("true");
    expect(screen.getByRole("tabpanel").getAttribute("aria-labelledby")).toBe(board.id);
    fireEvent.keyDown(board, { key: "ArrowLeft" });
    await screen.findByRole("combobox", { name: "Show orders" });
    const grid = screen.getByRole("tab", { name: "Daily entry" });
    expect(grid.getAttribute("aria-selected")).toBe("true");
    expect(document.activeElement).toBe(grid);
    expect(screen.getByRole("tabpanel").getAttribute("aria-labelledby")).toBe(grid.id);
  });
  it("discards a late context read and selection when browser history changes the work source", async () => {
    let finish;
    f.api.context.mockImplementationOnce(() => new Promise(resolve => { finish = resolve; }));
    mount("/manufacturing/daily", true);
    const accepted = await screen.findByRole("textbox", { name: "Accepted today PRO-7" });
    fireEvent.change(accepted, { target: { value: "10" } });
    fireEvent.click(screen.getByRole("checkbox", { name: "Select for review PRO-7" }));
    fireEvent.click(screen.getByRole("button", { name: "Review selected (1)" }));
    await waitFor(() => expect(f.api.context).toHaveBeenCalledOnce());
    const signal = f.api.context.mock.calls[0][1].signal;
    fireEvent.click(screen.getByRole("button", { name: "Browser navigation probe" }));
    expect(signal.aborted).toBe(true);
    await act(async () => finish(context(order)));
    expect(screen.queryByRole("dialog")).toBeNull();
    expect(screen.getByRole("button", { name: "Review selected (0)" }).disabled).toBe(true);
    expect(f.api.complete).not.toHaveBeenCalled();
  });
});
