const createTheme = ({
  accent,
  accentClasses,
  description,
  id,
  name,
  sidebar,
}) => {
  const isLight = sidebar.mode === "light";

  return {
    accent: {
      ...accent,
      ...accentClasses,
    },
    classes: isLight
      ? {
          activePill: accentClasses.lightClassName,
          brandSubtitle: sidebar.subtitleText,
          brandTile: `${accentClasses.className} text-white shadow-sm`,
          brandTitle: "text-slate-950",
          emptyBody: "text-slate-500",
          emptyCard: `border border-dashed ${sidebar.border} bg-white/70`,
          emptyTitle: "text-slate-800",
          footer: sidebar.border,
          iconActive: accentClasses.textClassName,
          iconInactive: `${sidebar.iconText} ${sidebar.iconHoverText}`,
          menuLabel: sidebar.sectionText,
          navActive: accentClasses.textClassName,
          navGroupActive: `${accentClasses.lightClassName} ${accentClasses.textClassName}`,
          navInactive: `${sidebar.navText} ${sidebar.navHoverBg} ${sidebar.navHoverText}`,
          noMatch: "bg-white/70 text-slate-500",
          root: `${sidebar.border} ${sidebar.root}`,
          searchIcon: sidebar.sectionText,
          searchInput: `${sidebar.searchBorder} bg-white text-slate-900 placeholder:text-slate-400 focus:border-brand focus:ring-brand/20`,
          searchShortcut: `${sidebar.searchBorder} ${accentClasses.lightClassName} ${accentClasses.textClassName}`,
          userAvatar: `${accentClasses.className} text-white`,
          userCard: "bg-white/70",
          userName: "text-slate-900",
          userRole: sidebar.subtitleText,
        }
      : {
          activePill: accentClasses.className,
          brandSubtitle: sidebar.subtitleText,
          brandTile: `${accentClasses.className} text-white shadow-sm`,
          brandTitle: "text-white",
          emptyBody: sidebar.subtitleText,
          emptyCard: `border border-dashed ${sidebar.border} ${sidebar.emptyBg}`,
          emptyTitle: "text-white",
          footer: sidebar.border,
          iconActive: "text-white",
          iconInactive: `${sidebar.iconText} group-hover:text-white`,
          menuLabel: sidebar.subtitleText,
          navActive: "text-white",
          navGroupActive: `${accentClasses.className} text-white`,
          navInactive: `${sidebar.navText} ${sidebar.navHoverBg} hover:text-white`,
          noMatch: `${sidebar.emptyBg} ${sidebar.navText}`,
          root: `${sidebar.border} ${sidebar.root}`,
          searchIcon: sidebar.subtitleText,
          searchInput: `${sidebar.searchBorder} ${sidebar.searchBg} text-white ${sidebar.placeholderText} focus:border-brand focus:ring-brand/30`,
          searchShortcut: `${sidebar.searchBorder} ${sidebar.shortcutBg} ${sidebar.subtitleText}`,
          userAvatar: `${accentClasses.className} text-white`,
          userCard: sidebar.userCard,
          userName: "text-white",
          userRole: sidebar.subtitleText,
        },
    description,
    id,
    name,
    preview: {
      accent: accentClasses.className,
      accentLight: accentClasses.lightClassName,
      border: accentClasses.borderClassName,
      button: accentClasses.className,
      content: "bg-white",
      line: sidebar.previewLine,
      muted: sidebar.previewMuted,
      root: sidebar.root,
      shadow: accentClasses.shadowClassName,
      sidebarText: isLight ? "bg-slate-400" : "bg-white/45",
    },
    sidebar,
  };
};

const darkSidebar = ({
  border,
  emptyBg,
  iconText,
  navHoverBg,
  navText,
  placeholderText,
  previewLine,
  previewMuted,
  root,
  searchBg,
  shortcutBg,
  subtitleText,
  userCard,
}) => ({
  border,
  emptyBg,
  iconText,
  mode: "dark",
  navHoverBg,
  navText,
  placeholderText,
  previewLine,
  previewMuted,
  root,
  searchBg,
  searchBorder: border,
  sectionText: subtitleText,
  shortcutBg,
  subtitleText,
  userCard,
});

const lightSidebar = ({
  border,
  iconHoverText,
  iconText,
  navHoverBg,
  navHoverText,
  navText,
  previewLine,
  previewMuted,
  root,
  sectionText,
  subtitleText,
}) => ({
  border,
  iconHoverText,
  iconText,
  mode: "light",
  navHoverBg,
  navHoverText,
  navText,
  previewLine,
  previewMuted,
  root,
  searchBorder: border,
  sectionText,
  subtitleText,
});

